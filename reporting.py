def generate_pdf_report(dataset_info, quality_before: dict, quality_after: dict,
                         issues_detected: list, operations_applied: list,
                         validation_warnings: list) -> bytes:
    """Generate a comprehensive PDF data quality report using ReportLab."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=72, leftMargin=72,
                            topMargin=72, bottomMargin=18)
    
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle('Title', parent=styles['Heading1'], textColor=navy)
    heading_style = ParagraphStyle('Heading', parent=styles['Heading2'], textColor=teal)
    normal_style = styles['Normal']
    
    elements = []
    
    elements.append(Paragraph("CleanSheet AI - Data Quality Report", title_style))
    if hasattr(dataset_info, 'filename'):
        dataset_name = dataset_info.filename
        rows_cnt = dataset_info.row_count
        cols_cnt = dataset_info.col_count
    elif isinstance(dataset_info, dict):
        dataset_name = dataset_info.get('name', 'Dataset')
        rows_cnt = dataset_info.get('rows', 0)
        cols_cnt = dataset_info.get('columns', 0)
    else:
        dataset_name = 'Dataset'
        rows_cnt = 0
        cols_cnt = 0

    elements.append(Paragraph(f"Dataset: {dataset_name}", styles['Heading3']))
    elements.append(Paragraph(f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", normal_style))
    elements.append(Spacer(1, 0.25*inch))
    
    elements.append(Paragraph("Dataset Summary", heading_style))
    summary_data = [
        ['Rows', rows_cnt],
        ['Columns', cols_cnt]
    ]
    t = Table(summary_data, colWidths=[2*inch, 2*inch])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), white),
        ('TEXTCOLOR', (0, 0), (-1, -1), black),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('FONTNAME', (0, 0), (-1, -1), 'Helvetica'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(t)
    elements.append(Spacer(1, 0.25*inch))
    
    elements.append(Paragraph("Before/After Metrics", heading_style))
    metrics_data = [
        ['Metric', 'Before', 'After'],
        ['Missing Values', quality_before.get('missing_cells', 0), quality_after.get('missing_cells', 0)],
        ['Duplicates', quality_before.get('duplicate_rows', 0), quality_after.get('duplicate_rows', 0)],
        ['Quality Score', f"{quality_before.get('quality_score', 0):.2f}", f"{quality_after.get('quality_score', 0):.2f}"]
    ]
    t2 = Table(metrics_data, colWidths=[2*inch, 1.5*inch, 1.5*inch])
    t2.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), navy),
        ('TEXTCOLOR', (0, 0), (-1, 0), white),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 12),
        ('BACKGROUND', (0, 1), (-1, -1), white),
        ('GRID', (0,0), (-1,-1), 1, grey)
    ]))
    elements.append(t2)
    elements.append(Spacer(1, 0.25*inch))
    
    if issues_detected:
        elements.append(Paragraph("Issues Detected", heading_style))
        for issue in issues_detected:
            elements.append(Paragraph(f"- {issue.get('description', 'Unknown issue')} (Severity: {issue.get('severity', 'Info')})", normal_style))
        elements.append(Spacer(1, 0.25*inch))
        
    if operations_applied:
        elements.append(Paragraph("Cleaning Operations Performed", heading_style))
        for i, op in enumerate(operations_applied, 1):
            elements.append(Paragraph(f"{i}. {op.get('description', op.get('operation', 'Unknown'))}", normal_style))
        elements.append(Spacer(1, 0.25*inch))
        
    if validation_warnings:
        elements.append(Paragraph("Validation Warnings", heading_style))
        for warn in validation_warnings:
            elements.append(Paragraph(f"! {warn}", normal_style))
            
    elements.append(Spacer(1, 0.5*inch))
    elements.append(Paragraph("Report Generated by CleanSheet AI", styles['Italic']))
    
    doc.build(elements)
    return buffer.getvalue()

def sanitize_dataframe_for_export(df: pd.DataFrame) -> pd.DataFrame:
    """Sanitize all string values to prevent formula injection."""
    df_sanitized = df.copy()
    forbidden_prefixes = ('=', '+', '-', '@', '\t', '\r')
    
    for col in df_sanitized.columns:
        is_str_col = pd.api.types.is_object_dtype(df_sanitized[col]) or pd.api.types.is_string_dtype(df_sanitized[col]) or not pd.api.types.is_numeric_dtype(df_sanitized[col])
        if is_str_col:
            df_sanitized[col] = df_sanitized[col].apply(
                lambda x: f"'{x}" if isinstance(x, str) and x.startswith(forbidden_prefixes) else x
            )
    return df_sanitized

def export_clean_csv(df: pd.DataFrame, sanitize: bool = True) -> bytes:
    """Export DataFrame as CSV bytes."""
    if sanitize:
        df = sanitize_dataframe_for_export(df)
    buffer = io.BytesIO()
    df.to_csv(buffer, index=False, encoding='utf-8')
    return buffer.getvalue()

def export_clean_excel(df: pd.DataFrame, sheet_name: str = 'Cleaned Data',
                        sanitize: bool = True) -> bytes:
    """Export DataFrame as Excel bytes."""
    if sanitize:
        df = sanitize_dataframe_for_export(df)
    
    wb = Workbook()
    ws = wb.active
    ws.title = sheet_name
    
    for r in dataframe_to_rows(df, index=False, header=True):
        ws.append(r)
        
    for cell in ws[1]:
        cell.font = Font(bold=True)
        
    id_col_indices = set()
    id_keywords = ('id', 'code', 'sku', 'zip', 'postal', 'phone')
    for idx, col_name in enumerate(df.columns, 1):
        if any(kw in str(col_name).lower() for kw in id_keywords):
            id_col_indices.add(idx)

    for col_idx, col in enumerate(ws.columns, 1):
        max_length = 0
        column = col[0].column_letter 
        for row_idx, cell in enumerate(col, 1):
            if row_idx > 1 and col_idx in id_col_indices:
                cell.number_format = '@'
                if cell.value is not None:
                    cell.value = str(cell.value)
            try:
                if len(str(cell.value)) > max_length:
                    max_length = len(str(cell.value))
            except:
                pass
        adjusted_width = (max_length + 2)
        ws.column_dimensions[column].width = adjusted_width

        
    buffer = io.BytesIO()
    wb.save(buffer)
    return buffer.getvalue()

def export_cleaning_history(change_history: list) -> str:
    """Export cleaning history as formatted JSON string."""
    return json.dumps(change_history, indent=4)

def generate_comparison_data(original_df: pd.DataFrame, cleaned_df: pd.DataFrame) -> dict:
    """Generate before/after comparison data."""
    cells_changed = 0
    common_cols = [c for c in original_df.columns if c in cleaned_df.columns]
    common_rows = min(len(original_df), len(cleaned_df))
    if common_cols and common_rows > 0:
        try:
            sub_orig = original_df.iloc[:common_rows][common_cols].astype(str)
            sub_clean = cleaned_df.iloc[:common_rows][common_cols].astype(str)
            cells_changed = int((sub_orig != sub_clean).sum().sum())
        except Exception:
            cells_changed = 0

    return {
        'rows_original': len(original_df),
        'rows_cleaned': len(cleaned_df),
        'cols_original': len(original_df.columns),
        'cols_cleaned': len(cleaned_df.columns),
        'missing_original': int(original_df.isna().sum().sum()),
        'missing_cleaned': int(cleaned_df.isna().sum().sum()),
        'missing_change': int(original_df.isna().sum().sum() - cleaned_df.isna().sum().sum()),
        'duplicates_original': int(original_df.duplicated().sum()),
        'duplicates_cleaned': int(cleaned_df.duplicated().sum()),
        'cells_changed': cells_changed,
        'quality_score_original': 0.0,
        'quality_score_cleaned': 0.0
    }
